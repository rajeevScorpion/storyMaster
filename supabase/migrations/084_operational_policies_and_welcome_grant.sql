-- 084_operational_policies_and_welcome_grant.sql
-- Store operational decisions as versioned, auditable policies and replace the
-- recurring free allowance with a one-time welcome grant.

CREATE TABLE IF NOT EXISTS public.operational_policies (
  policy_key text PRIMARY KEY CHECK (policy_key ~ '^[a-z][a-z0-9_]*$'),
  name text NOT NULL CHECK (char_length(btrim(name)) > 0),
  category text NOT NULL CHECK (category ~ '^[a-z][a-z0-9_]*$'),
  description text NOT NULL DEFAULT '',
  enabled boolean NOT NULL DEFAULT false,
  config_json jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(config_json) = 'object'),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.operational_policy_audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_key text NOT NULL REFERENCES public.operational_policies(policy_key) ON DELETE RESTRICT,
  policy_version integer NOT NULL CHECK (policy_version > 0),
  actor_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action_type text NOT NULL CHECK (action_type IN ('policy_created', 'policy_updated')),
  reason text NOT NULL CHECK (char_length(btrim(reason)) >= 4),
  before_json jsonb,
  after_json jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_operational_policy_audit_lookup
  ON public.operational_policy_audit_events (policy_key, created_at DESC, id DESC);

ALTER TABLE public.operational_policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.operational_policy_audit_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.operational_policies FROM anon, authenticated;
REVOKE ALL ON TABLE public.operational_policy_audit_events FROM anon, authenticated;
GRANT ALL ON TABLE public.operational_policies TO service_role;
GRANT ALL ON TABLE public.operational_policy_audit_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.operational_policy_audit_events_id_seq TO service_role;

