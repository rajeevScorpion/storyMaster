const US_STATE_CODE_SET: ReadonlySet<string> = new Set(US_STATES.map((entry) => entry.code));

export function isValidUsStateCode(code: string | null | undefined): code is string {
  return typeof code === 'string' && US_STATE_CODE_SET.has(code.trim().toUpperCase());
}

export function usStateName(code: string | null | undefined): string | null {
  if (!code) return null;
  return US_STATES.find((entry) => entry.code === code.trim().toUpperCase())?.name ?? null;
}
